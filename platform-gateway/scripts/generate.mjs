#!/usr/bin/env node
// Generates the gateway config from routes.yaml:
//   nginx/templates/routes.conf.template   (envsubst'd by the nginx image at start-up)
//   public/apps.json                       (runtime app registry, served at /platform/apps.json)
//   upstreams/docker.env, upstreams/dev.env
// `--check` fails if the committed output is stale (run it in CI).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const RESERVED = ["/platform", "/healthz", "/_next", "/api"];
const ID = /^[a-z][a-z0-9-]{1,30}$/;
const PATH = /^\/[a-z0-9-]+$/;

const { apps } = parse(readFileSync(join(root, "routes.yaml"), "utf8"));
validate(apps);

const envName = (app, kind) => `${app.id.toUpperCase().replace(/-/g, "_")}_${kind}_UPSTREAM`;
const upstreams = apps.flatMap((app) =>
  [
    ["WEB", app.web],
    ["API", app.api],
  ]
    .filter(([, target]) => target)
    .map(([kind, target]) => ({ name: envName(app, kind), docker: `${target.service}:${target.port}`, dev: `host.docker.internal:${target.devPort}` })),
);

const location = (comment, pattern, app, kind) => `  # ${comment}
  location ~ ${pattern} {
    set $upstream "\${${envName(app, kind)}}";
    proxy_pass http://$upstream;
    include /etc/nginx/snippets/proxy.conf;${kind === "API" ? "\n    error_page 502 503 504 = @api_unavailable;" : ""}
  }`;

const blocks = [];
// APIs first: /api/<id> must win over any web basePath.
for (const app of apps.filter((a) => a.api)) {
  blocks.push(location(`${app.id} API — ${app.team}`, `^${app.api.path}(/|$)`, app, "API"));
}
for (const app of apps.filter((a) => a.basePath !== "/")) {
  blocks.push(location(`${app.id} web — ${app.team}`, `^${app.basePath}(/|$)`, app, "WEB"));
}
const rootApp = apps.find((a) => a.basePath === "/");
for (const extra of rootApp?.extraPaths ?? []) {
  blocks.push(location(`${rootApp.id} ${extra}`, `^${extra}(/|$)`, rootApp, "WEB"));
}

const conf = `# GENERATED by scripts/generate.mjs from routes.yaml — do not edit by hand.

map $http_x_request_id $platform_request_id {
  default $http_x_request_id;
  ""      $request_id;
}

map $http_upgrade $connection_upgrade {
  default upgrade;
  ""      close;
}

server {
  listen 80;
  server_name _;

  # Resolve upstreams at request time so one app being down never stops the gateway booting.
  resolver \${NGINX_RESOLVER} valid=10s ipv6=off;

  include /etc/nginx/snippets/security-headers.conf;

  location = /healthz {
    access_log off;
    default_type application/json;
    return 200 '{"status":"ok"}';
  }

  # Runtime app registry + gateway error pages.
  location ^~ /platform/ {
    alias /usr/share/nginx/platform/;
    include /etc/nginx/snippets/security-headers.conf;
    add_header Cache-Control "public, max-age=30" always;
  }

  error_page 502 503 504 /platform/unavailable.html;

  location @api_unavailable {
    default_type application/json;
    return 503 '{"error":"service_unavailable","requestId":"$platform_request_id"}';
  }

${blocks.join("\n\n")}
${
  rootApp
    ? `
  # ${rootApp.id} — everything else
  location / {
    set $upstream "\${${envName(rootApp, "WEB")}}";
    proxy_pass http://$upstream;
    include /etc/nginx/snippets/proxy.conf;
  }`
    : ""
}
}
`;

const registry = {
  generatedFrom: "routes.yaml",
  apps: apps.map(({ id, title, description, team, icon, basePath }) => ({ id, title, description, team, icon, basePath })),
};

const outputs = {
  "nginx/templates/routes.conf.template": conf,
  "public/apps.json": JSON.stringify(registry, null, 2) + "\n",
  "upstreams/docker.env": upstreams.map((u) => `${u.name}=${u.docker}`).join("\n") + "\nNGINX_RESOLVER=127.0.0.11\n",
  "upstreams/dev.env": upstreams.map((u) => `${u.name}=${u.dev}`).join("\n") + "\nNGINX_RESOLVER=127.0.0.11\n",
};

let stale = [];
for (const [file, content] of Object.entries(outputs)) {
  const path = join(root, file);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== content) stale.push(file);
  } else {
    writeFileSync(path, content);
    console.log(`wrote ${file}`);
  }
}
if (stale.length) {
  console.error(`Generated files are stale: ${stale.join(", ")}. Run \`pnpm generate\` and commit.`);
  process.exit(1);
}

function validate(apps) {
  const errors = [];
  const ids = new Set();
  const paths = new Set();
  if (!Array.isArray(apps) || apps.length === 0) errors.push("routes.yaml must define at least one app");
  for (const app of apps ?? []) {
    const where = `app "${app.id}"`;
    if (!ID.test(app.id ?? "")) errors.push(`${where}: id must match ${ID}`);
    if (ids.has(app.id)) errors.push(`${where}: duplicate id`);
    ids.add(app.id);
    if (!app.title) errors.push(`${where}: title is required`);
    if (app.basePath !== "/" && !PATH.test(app.basePath ?? "")) errors.push(`${where}: basePath must be "/" or match ${PATH}`);
    if (RESERVED.includes(app.basePath)) errors.push(`${where}: basePath ${app.basePath} is reserved`);
    for (const p of [app.basePath, ...(app.extraPaths ?? [])]) {
      if (paths.has(p)) errors.push(`${where}: path ${p} is already taken`);
      paths.add(p);
    }
    if (!app.web?.service || !app.web?.port || !app.web?.devPort) errors.push(`${where}: web.service, web.port and web.devPort are required`);
    if (app.api) {
      if (app.api.path !== `/api/${app.id}`) errors.push(`${where}: api.path must be /api/${app.id}`);
      if (!app.api.service || !app.api.port || !app.api.devPort) errors.push(`${where}: api.service, api.port and api.devPort are required`);
    }
    if (app.extraPaths && app.basePath !== "/") errors.push(`${where}: only the root app may claim extraPaths`);
  }
  if (apps?.filter((a) => a.basePath === "/").length > 1) errors.push("only one app may own basePath /");
  if (errors.length) {
    console.error("routes.yaml is invalid:\n  - " + errors.join("\n  - "));
    process.exit(1);
  }
}
